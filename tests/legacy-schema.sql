-- Additive baseline; run as the application migration credential under shared lock.
BEGIN;
SET LOCAL ROLE dunamismax_owner;
CREATE TABLE IF NOT EXISTS app.posts (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 slug varchar(180) COLLATE "C" NOT NULL UNIQUE CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
 title varchar(240) NOT NULL,
 excerpt varchar(600) NOT NULL DEFAULT '',
 body text NOT NULL CHECK (octet_length(body) <= 16777215),
 status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'published')),
 published_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CHECK (status <> 'published' OR published_at IS NOT NULL)
);
CREATE INDEX IF NOT EXISTS posts_publication ON app.posts (status, published_at DESC, id DESC);
CREATE OR REPLACE VIEW app.public_posts WITH (security_barrier=true) AS
 SELECT id, slug, title, excerpt, body, published_at FROM app.posts
 WHERE status = 'published' AND published_at <= CURRENT_TIMESTAMP;
REVOKE ALL ON app.posts FROM dunamismax_web;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA app FROM dunamismax_web;
GRANT SELECT ON app.public_posts TO dunamismax_web;
GRANT SELECT, INSERT, UPDATE ON app.posts TO dunamismax_publishing;
GRANT USAGE ON SEQUENCE app.posts_id_seq TO dunamismax_publishing;
COMMIT;
